const pad = (value) => String(value).padStart(2, '0');

const MONTH_ABBR = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const MONTH_RE_SRC = 'jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec';
// "Oct 31, 2026" / "Oct 31 2026" / "31 Oct 2026" — the older TikTok Studio date field.
const MONTH_NAME_DATE_RE = new RegExp(
    `\\b(?:(?:${MONTH_RE_SRC})[a-z]*\\.?\\s+\\d{1,2}|\\d{1,2}\\s+(?:${MONTH_RE_SRC})[a-z]*\\.?)\\b[\\s,]+\\d{4}\\b`,
    'i'
);

const FIVE_MINUTES_IN_MS = 5 * 60 * 1000;

// TikTok Studio's minute picker only offers 00,05,...,55, so any random spread
// has to be a whole number of 5-minute steps. `jitterSteps` is the maximum
// number of extra 5-minute steps added on top of the configured interval
// (0 = exact interval, the historical behaviour). With jitter the result is
// snapped to the 5-minute grid instead of the interval grid, so a 10-minute
// interval can still land on :15 or :25 like a hand-made schedule would.
function scheduleJitterMs(jitterSteps, random) {
    const steps = Math.max(0, Math.floor(Number(jitterSteps) || 0));
    if (steps === 0) return 0;
    return Math.floor(random() * (steps + 1)) * FIVE_MINUTES_IN_MS;
}

function snapToGrid(time, gridMs) {
    return new Date(Math.ceil(time.getTime() / gridMs) * gridMs);
}

export function computeNextScheduledTime({ index, lastScheduledTime, intervalMinutes = 10, now = new Date(), jitterSteps = 0, random = Math.random }) {
    if (index < 3) return null;
    const stepMin = Number(intervalMinutes) === 5 ? 5 : 10;
    const stepMs = stepMin * 60 * 1000;
    const TWENTY_MINUTES_IN_MS = 20 * 60 * 1000;
    const jitter = scheduleJitterMs(jitterSteps, random);

    const baseTime = index === 3 || !lastScheduledTime
        ? new Date(now.getTime() + TWENTY_MINUTES_IN_MS + jitter)
        : new Date(lastScheduledTime.getTime() + stepMs + jitter);

    return snapToGrid(baseTime, jitterSteps > 0 ? FIVE_MINUTES_IN_MS : stepMs);
}

export function computeAutoIncrementTime({ lastScheduledTime, intervalMinutes = 5, now = new Date(), jitterSteps = 0, random = Math.random }) {
    const stepMin = Number(intervalMinutes) === 10 ? 10 : (Number(intervalMinutes) || 5);
    const stepMs = stepMin * 60 * 1000;
    const TWENTY_MINUTES_IN_MS = 20 * 60 * 1000;
    const jitter = scheduleJitterMs(jitterSteps, random);

    let baseTime;
    if (lastScheduledTime && lastScheduledTime instanceof Date && !Number.isNaN(lastScheduledTime.getTime())) {
        let validLastTime = new Date(lastScheduledTime.getTime());
        if (validLastTime.getFullYear() < 2020) {
            validLastTime.setFullYear(now.getFullYear());
        }
        baseTime = new Date(validLastTime.getTime() + stepMs + jitter);
    } else {
        baseTime = new Date(now.getTime() + TWENTY_MINUTES_IN_MS + jitter);
    }

    return snapToGrid(baseTime, jitterSteps > 0 ? FIVE_MINUTES_IN_MS : stepMs);
}

export function getScheduleHintText(meta = {}) {
    return [
        meta.placeholder,
        meta.ariaLabel,
        meta.label,
        meta.name,
        // meta.id, // Exclude ID to avoid matching autogenerated prefixes like :rc4:
        meta.value
    ]
        .filter(Boolean)
        .join(' ')
        .toLowerCase();
}

export function inferScheduleFieldKind(meta = {}) {
    const hint = getScheduleHintText(meta);
    if (!hint) return 'unknown';

    // Priority 0: the older UI adds a third control, "(GMT+7) Local Time". It
    // contains the word "time", so without this it is claimed as the time field.
    if (/\b(gmt|utc)\b/.test(hint) || /local time|time\s?zone/.test(hint)) return 'timezone';

    // Priority 1: explicitly mentions date/time words
    if (/\b(date|day|ngay)\b/.test(hint)) return 'date';
    if (/\b(time|hour|minute|gio)\b/.test(hint)) return 'time';

    // Priority 2: Looks like a Date pattern (YYYY-MM-DD, MM/DD/YYYY, etc.)
    if (/\d{4}[-.]\d{2}[-.]\d{2}/.test(hint) || /\d{1,2}[\/-]\d{1,2}[\/-]\d{2,4}/.test(hint)) {
        return 'date';
    }

    // Priority 2b: month-name dates — the older Studio UI renders "Oct 31, 2026"
    // (and "31 Oct 2026" in some locales), which matches none of the numeric
    // patterns above and used to fall through as 'unknown'.
    if (MONTH_NAME_DATE_RE.test(hint)) {
        return 'date';
    }

    // Priority 3: Looks like a Time pattern (HH:mm)
    if (/\b(am|pm)\b/.test(hint) || /\b\d{1,2}:\d{2}\b/.test(hint)) {
        return 'time';
    }

    return 'unknown';
}


export function formatScheduleValue(date, kind, meta = {}) {
    if (!(date instanceof Date) || Number.isNaN(date.getTime())) {
        throw new Error('Invalid schedule date');
    }

    const hint = getScheduleHintText(meta);
    const year = date.getFullYear();
    const month = pad(date.getMonth() + 1);
    const day = pad(date.getDate());
    const hours = date.getHours();
    const minutes = pad(date.getMinutes());

    if (kind === 'time') {
        if (/\b(am|pm)\b/.test(hint)) {
            const hour12 = hours % 12 || 12;
            const meridiem = hours >= 12 ? 'PM' : 'AM';
            return `${hour12}:${minutes} ${meridiem}`;
        }

        return `${pad(hours)}:${minutes}`;
    }

    if (kind === 'date') {
        // Older Studio UI renders the date as "Oct 31, 2026"; typing an ISO string
        // into that field is rejected, so mirror whatever shape the field already has.
        if (MONTH_NAME_DATE_RE.test(hint)) {
            return `${MONTH_ABBR[date.getMonth()]} ${date.getDate()}, ${year}`;
        }
        if (/dd\s*\/\s*mm/.test(hint)) return `${day}/${month}/${year}`;
        if (/mm\s*\/\s*dd/.test(hint) || hint.includes('/')) return `${month}/${day}/${year}`;
        if (hint.includes('.')) return `${year}.${month}.${day}`;
        return `${year}-${month}-${day}`;
    }

    throw new Error(`Unsupported schedule field kind: ${kind}`);
}

export function sortScheduleInputs(inputs = []) {
    return [...inputs].sort((a, b) => {
        if ((a.top ?? 0) !== (b.top ?? 0)) return (a.top ?? 0) - (b.top ?? 0);
        return (a.left ?? 0) - (b.left ?? 0);
    });
}

/**
 * Robustly parses time text extracted from TikTok Studio Content page (e.g. "Sep 6, 02:30", "06/09 02:30", "6 thg 9, 02:30").
 * Always ensures the year is set to the current year (or future year) and not 2001.
 */
export function parseTikTokContentTimeText(timeText) {
    if (!timeText) return null;

    const now = new Date();
    const currentYear = now.getFullYear();

    // Standard JS Date parse check
    let d = new Date(timeText);
    if (!Number.isNaN(d.getTime())) {
        if (d.getFullYear() < 2020) {
            d.setFullYear(currentYear);
        }
        return d;
    }

    // Handle Vietnamese format "6 thg 9, 02:30" or "06 thg 09 02:30"
    const vnMatch = timeText.match(/(\d{1,2})\s*thg\s*(\d{1,2})[\s,]+(\d{1,2}):(\d{2})(?:\s*(AM|PM))?/i);
    if (vnMatch) {
        const day = parseInt(vnMatch[1], 10);
        const month = parseInt(vnMatch[2], 10);
        let hours = parseInt(vnMatch[3], 10);
        const minutes = parseInt(vnMatch[4], 10);
        const meridiem = vnMatch[5];
        if (meridiem) {
            if (meridiem.toUpperCase() === 'PM' && hours < 12) hours += 12;
            if (meridiem.toUpperCase() === 'AM' && hours === 12) hours = 0;
        }
        const res = new Date();
        res.setFullYear(currentYear, month - 1, day);
        res.setHours(hours, minutes, 0, 0);
        return res;
    }

    // Handle Month name format "Sep 6, 02:30" or "Sep 6, 2:30 PM"
    const monthsMap = { jan: 0, feb: 1, mar: 2, apr: 3, may: 4, jun: 5, jul: 6, aug: 7, sep: 8, oct: 9, nov: 10, dec: 11 };
    const monthMatch = timeText.match(/([a-z]{3,9})\s+(\d{1,2})[\s,]+(\d{1,2}):(\d{2})(?:\s*(AM|PM))?/i);
    if (monthMatch) {
        const mStr = monthMatch[1].toLowerCase().slice(0, 3);
        if (monthsMap[mStr] !== undefined) {
            const month = monthsMap[mStr];
            const day = parseInt(monthMatch[2], 10);
            let hours = parseInt(monthMatch[3], 10);
            const minutes = parseInt(monthMatch[4], 10);
            const meridiem = monthMatch[5];
            if (meridiem) {
                if (meridiem.toUpperCase() === 'PM' && hours < 12) hours += 12;
                if (meridiem.toUpperCase() === 'AM' && hours === 12) hours = 0;
            }
            const res = new Date();
            res.setFullYear(currentYear, month, day);
            res.setHours(hours, minutes, 0, 0);
            return res;
        }
    }

    // Handle numeric format "09/06 02:30" or "2026-09-06 02:30"
    const numMatch = timeText.match(/(?:(\d{4})[-/.])?(\d{1,2})[-/.](\d{1,2})[\s,]+(\d{1,2}):(\d{2})(?:\s*(AM|PM))?/i);
    if (numMatch) {
        const yr = numMatch[1] ? parseInt(numMatch[1], 10) : currentYear;
        const partA = parseInt(numMatch[2], 10);
        const partB = parseInt(numMatch[3], 10);
        let hours = parseInt(numMatch[4], 10);
        const minutes = parseInt(numMatch[5], 10);
        const meridiem = numMatch[6];
        if (meridiem) {
            if (meridiem.toUpperCase() === 'PM' && hours < 12) hours += 12;
            if (meridiem.toUpperCase() === 'AM' && hours === 12) hours = 0;
        }

        let month = partA;
        let day = partB;
        if (partA > 12) {
            day = partA;
            month = partB;
        }

        const res = new Date();
        res.setFullYear(yr < 2020 ? currentYear : yr, month - 1, day);
        res.setHours(hours, minutes, 0, 0);
        return res;
    }

    return null;
}

/**
 * Attempts to parse a date and time string from TikTok inputs back into a Date object.
 */
export function parseScheduleValue(dateStr, timeStr) {
    if (!dateStr || !timeStr) return null;

    try {
        const now = new Date();
        let year = now.getFullYear();
        let month, day;

        if (dateStr.includes('-')) {
            const parts = dateStr.split('-').map(Number);
            if (parts[0] > 1000) {
                [year, month, day] = parts;
            } else {
                [month, day, year] = parts;
            }
        } else if (dateStr.includes('/')) {
            const parts = dateStr.split('/').map(Number);
            if (parts[2] > 1000) {
                year = parts[2];
                if (parts[0] > 12) {
                    day = parts[0];
                    month = parts[1];
                } else if (parts[1] > 12) {
                    month = parts[0];
                    day = parts[1];
                } else {
                    month = parts[0];
                    day = parts[1];
                }
            } else {
                month = parts[0];
                day = parts[1];
            }
        } else if (dateStr.includes('.')) {
            const parts = dateStr.split('.').map(Number);
            if (parts[0] > 1000) {
                [year, month, day] = parts;
            } else {
                [day, month, year] = parts;
            }
        }

        if (!year || year < 2020) {
            year = now.getFullYear();
        }

        // Try to parse time (expected HH:mm or HH:mm AM/PM)
        let hours, minutes;
        const timeMatch = timeStr.match(/(\d{1,2}):(\d{2})(?:\s*(AM|PM))?/i);
        if (!timeMatch) return null;

        hours = parseInt(timeMatch[1], 10);
        minutes = parseInt(timeMatch[2], 10);
        const meridiem = timeMatch[3];

        if (meridiem) {
            if (meridiem.toUpperCase() === 'PM' && hours < 12) hours += 12;
            if (meridiem.toUpperCase() === 'AM' && hours === 12) hours = 0;
        }

        // Set year/month/day in ONE call. Doing it field-by-field rolls the date
        // over whenever "today" is a day the target month does not have
        // (e.g. on Oct 31, setMonth(8) => Sep 31 => Oct 1, silently +1 month).
        const date = new Date();
        const finalYear = year || date.getFullYear();
        const finalMonth = month ? month - 1 : date.getMonth();
        const finalDay = day || date.getDate();
        date.setHours(hours, minutes, 0, 0);
        date.setFullYear(finalYear, finalMonth, finalDay);

        return date;
    } catch (e) {
        console.error('Error parsing schedule value:', e);
        return null;
    }
}

/**
 * True when `text` (whatever shape the field renders: "2026-11-01", "11/01/2026",
 * "Nov 1, 2026", ...) denotes the given calendar date.
 *
 * Verification cannot be a string compare: the same date is displayed differently
 * per UI variant, so comparing against our generated string reports a false
 * failure on the older month-name UI and triggers a destructive raw-fill fallback.
 */
export function displayedDateMatches(text, { year, month, day }) {
    if (!text) return false;
    const t = String(text).trim();

    const named = t.match(
        /(?:(jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*\.?\s+(\d{1,2})|(\d{1,2})\s+(jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*\.?)[\s,]+(\d{4})/i
    );
    if (named) {
        const name = (named[1] || named[4]).toLowerCase();
        return Number(named[5]) === year
            && MONTH_ABBR.findIndex((m) => m.toLowerCase() === name) + 1 === month
            && Number(named[2] || named[3]) === day;
    }

    const nums = t.match(/(\d{1,4})[-/.](\d{1,2})[-/.](\d{1,4})/);
    if (!nums) return false;
    const [a, b, c] = [Number(nums[1]), Number(nums[2]), Number(nums[3])];
    if (a > 31) return a === year && b === month && c === day;            // YYYY-MM-DD
    // DD/MM/YYYY vs MM/DD/YYYY is ambiguous; accept either reading.
    if (c > 31) return c === year && ((a === month && b === day) || (a === day && b === month));
    return false;
}

/**
 * Split a date string we generated (or read back) into calendar parts.
 *
 * Must understand every shape `formatScheduleValue` can emit — including the
 * older UI's "Nov 1, 2026". When it could not, the callers' month arithmetic
 * silently became NaN and the calendar navigation walked backwards to its
 * iteration cap instead of stopping.
 *
 * Returns NaN fields when the value cannot be parsed; callers must check.
 */
export function parseScheduleDateValue(value) {
    const nothing = { year: NaN, month: NaN, day: NaN };
    if (!value) return nothing;
    const text = String(value).trim();

    const named = text.match(
        /(?:(jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*\.?\s+(\d{1,2})|(\d{1,2})\s+(jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*\.?)[\s,]+(\d{4})/i
    );
    if (named) {
        const name = (named[1] || named[4]).toLowerCase();
        return {
            year: Number(named[5]),
            month: MONTH_ABBR.findIndex((m) => m.toLowerCase() === name) + 1,
            day: Number(named[2] || named[3])
        };
    }

    const parts = text.split(/[-/.]/).map(Number);
    if (parts.length < 3 || parts.some((n) => !Number.isFinite(n))) return nothing;
    if (/^\d{4}/.test(text)) return { year: parts[0], month: parts[1], day: parts[2] }; // YYYY-MM-DD
    if (parts[0] > 12) return { year: parts[2], month: parts[1], day: parts[0] };       // DD/MM/YYYY
    return { year: parts[2], month: parts[0], day: parts[1] };                          // MM/DD/YYYY
}

/** True when the parts form a usable calendar date. */
export function isValidScheduleDateParts({ year, month, day } = {}) {
    return Number.isInteger(year) && Number.isInteger(month) && Number.isInteger(day)
        && month >= 1 && month <= 12 && day >= 1 && day <= 31 && year >= 2000;
}

/** True when `text` ("00:00", "12:00 AM", ...) denotes the given wall-clock time. */
export function displayedTimeMatches(text, { hour, minute }) {
    if (!text) return false;
    const m = String(text).match(/(\d{1,2}):(\d{2})\s*(AM|PM)?/i);
    if (!m) return false;
    let h = Number(m[1]);
    if (m[3]) {
        if (/pm/i.test(m[3]) && h < 12) h += 12;
        if (/am/i.test(m[3]) && h === 12) h = 0;
    }
    return h === hour && Number(m[2]) === minute;
}

// A scheduled video's status label carries the target timezone -- "Nov 1, 12:50 AM
// (GMT+7) Saigon" -- while an already-published one shows only "Nov 1, 12:25 AM".
const SCHEDULED_LABEL_TZ_RE = /\((?:GMT|UTC)\s*[+-]?\d{0,2}(?::\d{2})?\)/i;

/**
 * True when a Content-page status label denotes a *scheduled* video.
 *
 * The previous test was `/\d{1,2}:\d{2}/`, which any published label also
 * satisfies ("Nov 1, 12:25 AM" contains "12:25"), so every published video was
 * read as scheduled and the upload flow took its publish time as the base.
 * Used for the variant that renders no Alarm icon; when the icon is present it
 * remains the primary signal.
 */
export function looksLikeScheduledLabel(text) {
    return !!text && SCHEDULED_LABEL_TZ_RE.test(String(text));
}

/**
 * Decide whether a Content-page status label belongs to a *scheduled* video.
 *
 * The two UI variants signal it differently and neither signal is universal, so
 * both are accepted:
 *   - older UI: an Alarm icon next to the time (the timezone suffix may be absent)
 *   - newer UI: no icon at all, but the time carries "(GMT+7) Saigon"
 * A published video has neither, in either UI.
 */
export function isScheduledStatusLabel({ hasAlarmIcon = false, labelText = '' } = {}) {
    return !!hasAlarmIcon || looksLikeScheduledLabel(labelText);
}
